#!/usr/bin/env python3
"""Generate core/src/font3x5.h from the glyph drawings below.

Mosura's type is a 3x5 pixel face (4x6 cell), drawn for this project. It is
small enough for 32 columns by 10 lines on the 128x64 OLED, which puts the
screen density close to the MPC2000XL's 240x64 LCD. Codes 1..15 are icons.
Lower case maps to upper case in the renderer.

    python3 tools/genfont.py
"""
